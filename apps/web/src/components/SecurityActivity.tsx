import { useMemo, useState, type ReactNode } from 'react';
import { Link } from 'react-router-dom';
import type { SecurityEvent, SecurityEventKind, SecurityEventSeverity, SecurityEventType } from '@credential-reaper/shared';
import { useNow } from '../hooks/useNow';
import { useSecurityActivity } from '../hooks/useSecurityActivity';
import { exactTime, relativeTime } from '../lib/time';
import { FeedIndicator } from './FeedIndicator';
import { FilterSelect } from './FilterSelect';
import { Panel } from './Panel';
import { StateMessage } from './StateMessage';
import { ArrowRight } from './Glyph';
import '../activity.css';

const TYPE_LABEL: Record<SecurityEventType, string> = {
  'investigation-started': 'Investigation started',
  'finding-discovered': 'Finding discovered',
  'investigation-completed': 'Investigation completed',
  'investigation-failed': 'Investigation failed',
  'remediation-proposed': 'Remediation proposed',
  'remediation-approved': 'Remediation approved',
  'remediation-rejected': 'Remediation rejected',
  'remediation-simulated': 'Remediation simulated (dry run)',
  'repo-scan-ingested': 'Repository scan ingested',
};

const KIND: Record<SecurityEventKind, { label: string; title: string }> = {
  observed: { label: 'Observed', title: 'Recorded by the system as a fact it observed.' },
  'ai-finding': { label: 'AI finding', title: 'A finding generated by the AI analyst during an investigation.' },
  'user-action': { label: 'User action', title: 'An action a person initiated.' },
};

const KIND_OPTIONS = [{ value: 'all', label: 'All' }, ...(Object.keys(KIND) as SecurityEventKind[]).map((k) => ({ value: k, label: KIND[k].label }))];
const SEVERITY_OPTIONS = [
  { value: 'all', label: 'All' },
  ...(['critical', 'high', 'medium', 'low', 'info'] as SecurityEventSeverity[]).map((s) => ({ value: s, label: s })),
];

function KindIcon({ kind }: { kind: SecurityEventKind }) {
  const shape =
    kind === 'observed' ? (
      <>
        <circle cx="8" cy="8" r="5.5" fill="none" stroke="currentColor" strokeWidth="1.6" />
        <circle cx="8" cy="8" r="1.6" fill="currentColor" />
      </>
    ) : kind === 'ai-finding' ? (
      <path d="M8 1.5 14.5 8 8 14.5 1.5 8Z" fill="none" stroke="currentColor" strokeWidth="1.6" />
    ) : (
      <rect x="2.5" y="2.5" width="11" height="11" fill="currentColor" />
    );
  return (
    <svg viewBox="0 0 16 16" aria-hidden="true" focusable="false">
      {shape}
    </svg>
  );
}

export function KindChip({ kind }: { kind: SecurityEventKind }) {
  return (
    <span className={`kind-chip kind-${kind}`} title={KIND[kind].title}>
      <KindIcon kind={kind} />
      {KIND[kind].label}
    </span>
  );
}

function SeverityBadge({ severity }: { severity: SecurityEventSeverity }) {
  return <span className={`badge badge-${severity === 'info' ? 'neutral' : severity}`}>{severity}</span>;
}

interface Props {
  /** Compact: latest few rows inside a panel, no filters, link to the full feed. */
  compact?: boolean;
}

export function SecurityActivity({ compact = false }: Props) {
  const feed = useSecurityActivity(compact ? 30 : 100);
  const now = useNow(true, 15_000);
  const [kind, setKind] = useState('all');
  const [severity, setSeverity] = useState('all');
  const [openIds, setOpenIds] = useState<ReadonlySet<string>>(new Set());
  const [frozen, setFrozen] = useState<ReadonlySet<string> | null>(null);
  const max = compact ? 6 : Infinity;

  const matching = useMemo(
    () => feed.events.filter((e) => (kind === 'all' || e.kind === kind) && (severity === 'all' || e.severity === severity)),
    [feed.events, kind, severity],
  );
  const live = useMemo(() => matching.slice(0, max), [matching, max]);
  // While a row is expanded the list is held still; new arrivals wait behind a "show" button.
  const shown = frozen ? matching.filter((e) => frozen.has(e.id)) : live;
  const waiting = frozen ? matching.filter((e) => !frozen.has(e.id)).length : 0;

  function onToggle(id: string, open: boolean) {
    const next = new Set(openIds);
    if (open) next.add(id);
    else next.delete(id);
    setOpenIds(next);
    if (open && !frozen) setFrozen(new Set(shown.map((e) => e.id)));
    if (next.size === 0) setFrozen(null);
  }

  const indicator = <FeedIndicator status={feed.transport} />;

  const body = (
    <>
      {feed.load === 'loading' && <StateMessage kind="loading">loading security activity…</StateMessage>}
      {feed.load === 'error' && (
        <StateMessage
          kind="error"
          actions={
            <button type="button" className="btn btn-sm" onClick={feed.reload}>
              Retry
            </button>
          }
        >
          {feed.error}
        </StateMessage>
      )}
      {feed.load === 'ready' && feed.transport === 'offline' && (
        <StateMessage kind="error">The API is unreachable. Showing the last events received; new events will not appear until it returns.</StateMessage>
      )}
      {feed.load === 'ready' && feed.events.length === 0 && <StateMessage kind="empty">no security activity recorded yet. Start an investigation to generate some.</StateMessage>}
      {feed.load === 'ready' && feed.events.length > 0 && matching.length === 0 && <StateMessage kind="empty">no events match these filters.</StateMessage>}

      {shown.length > 0 && (
        <ol className="secact-list" aria-label="Security events, newest first">
          {shown.map((e) => (
            <EventRow key={e.id} event={e} now={now} onToggle={onToggle} />
          ))}
        </ol>
      )}

      {waiting > 0 && (
        <div className="secact-newbar" role="status">
          <span>
            {waiting} new event{waiting === 1 ? '' : 's'} arrived while you were reading.
          </span>
          <button type="button" className="btn btn-secondary btn-sm" onClick={() => setFrozen(null)}>
            Show
          </button>
        </div>
      )}
    </>
  );

  if (compact) {
    return (
      <Panel title="Security activity" bracketed actions={indicator} className="secact-compact">
        {body}
        <Link to="/activity" className="btn btn-secondary btn-sm suggest-cta">
          Open full feed <ArrowRight />
        </Link>
      </Panel>
    );
  }

  return (
    <>
      <div className="secact-head">
        <div className="filter-bar">
          <FilterSelect label="Kind" value={kind} options={KIND_OPTIONS} onChange={setKind} />
          <FilterSelect label="Severity" value={severity} options={SEVERITY_OPTIONS} onChange={setSeverity} />
          {feed.load === 'ready' && (
            <span className="muted-sm" role="status">
              {matching.length} of {feed.events.length} shown
            </span>
          )}
        </div>
        {indicator}
      </div>
      {body}
    </>
  );
}

function EventRow({ event: e, now, onToggle }: { event: SecurityEvent; now: number; onToggle: (id: string, open: boolean) => void }) {
  const who: ReactNode = e.identityId ? (
    <Link to={`/identities/${encodeURIComponent(e.identityId)}`}>{e.identityName ?? e.identityId}</Link>
  ) : (
    <span className="muted">{e.identityName ?? 'no identity'}</span>
  );
  return (
    <li className="secact-item" style={{ listStyle: 'none' }}>
      <details className="disc" onToggle={(ev) => onToggle(e.id, (ev.currentTarget as HTMLDetailsElement).open)}>
        <summary className="disc-sum secact-sum">
          <time className="secact-time" dateTime={e.timestamp} title={exactTime(e.timestamp)}>
            {relativeTime(e.timestamp, now)}
          </time>
          <span className="secact-meta">
            {who}
            <span className="secact-type">{TYPE_LABEL[e.type] ?? e.type}</span>
            {e.severity && <SeverityBadge severity={e.severity} />}
            <KindChip kind={e.kind} />
            <span className="muted-sm">source: {e.source}</span>
          </span>
          <span className="secact-summary">{e.summary}</span>
        </summary>
        <div className="secact-body">
          <p>{e.details || 'No further details were recorded.'}</p>
          <dl>
            <dt>Time</dt>
            <dd>{exactTime(e.timestamp)}</dd>
            <dt>Actor</dt>
            <dd>{e.actor}</dd>
            {e.investigationId && (
              <>
                <dt>Investigation</dt>
                <dd className="mono">{e.investigationId}</dd>
              </>
            )}
            {e.remediationId && (
              <>
                <dt>Plan</dt>
                <dd className="mono">{e.remediationId}</dd>
              </>
            )}
          </dl>
        </div>
      </details>
    </li>
  );
}
